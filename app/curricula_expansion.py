def extend_curricula(curricula):
    """Append missing source curriculum topics while preserving current entries."""
    for slug, topics in CURRICULUM_EXPANSIONS.items():
        curriculum = curricula.get(slug)
        if curriculum is None:
            continue
        existing = curriculum.setdefault("topics", [])
        seen = {str(topic).strip().casefold() for topic in existing}
        for topic in topics:
            if not isinstance(topic, str) or not topic.strip():
                continue
            normalized = topic.strip().casefold()
            if normalized not in seen:
                existing.append(topic)
                seen.add(normalized)
